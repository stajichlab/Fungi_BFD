#!/usr/bin/env python3
"""Propose data/curation/out_suffix.csv rows that separate genomes sharing one `out` folder.

`out` (makeSampleTag(SPECIES, STRAIN)) names the per-genome results folder under
Fungi_BFD_runs/genome_annotation. Two samples.csv rows with the same `out` would
share predictions. Run create_samples_file.py with --clash-report first, then this
script with a reference samples.csv (the file the runs currently use).

Rules for each clash group (rows that share one `out`):
  * A row that is already in the reference samples.csv keeps the plain name.
  * Another row with HAPLOTYPE hap1/hap2 gets suffix 'hap1' / 'hap2'
    (strain becomes '<strain>_hap1', or just 'hap1' when the strain is empty).
  * Another row without a haplotype role whose ASMID contains 'hapN' gets 'hapN'.
  * Any other row gets SUFFIX 'HOLD': create_samples_file.py leaves it out of
    samples.csv until a person replaces HOLD with a real suffix.
  * A group with 2+ rows already in the reference is reported, not changed.
  * A group with no row in the reference: hap1/hap2 rows get suffixes and the
    others get HOLD.
Existing out_suffix.csv rows are never overwritten.

Default is a dry run. Use --write to update the file.
"""
import argparse
import collections
import csv
import os
import re
import sys


def read_existing(path):
    rows = collections.OrderedDict()
    if os.path.exists(path):
        with open(path, newline='') as f:
            lines = (l for l in f if l.strip() and not l.lstrip().startswith('#'))
            for r in csv.DictReader(lines):
                rows[r['ASMID']] = r
    return rows


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--clash-report', required=True)
    ap.add_argument('--reference', required=True, help='samples.csv currently used by the runs')
    ap.add_argument('--out', default='data/curation/out_suffix.csv')
    ap.add_argument('--write', action='store_true')
    args = ap.parse_args()

    with open(args.reference, newline='') as f:
        live = {r['ASMID'] for r in csv.DictReader(f)}
    groups = collections.defaultdict(list)
    with open(args.clash_report, newline='') as f:
        for r in csv.DictReader(f):
            if r['OUT']:
                groups[r['OUT']].append(r)

    existing = read_existing(args.out)
    new_rows, notes = [], []
    for out, rs in sorted(groups.items()):
        in_ref = [r for r in rs if r['ASMID'] in live]
        if len(in_ref) > 1:
            notes.append(f"PRE-EXISTING: {out}: {len(in_ref)} reference rows share it: "
                         + ', '.join(r['ASMID'] for r in in_ref))
            continue
        keeper = in_ref[0]['ASMID'] if in_ref else None
        for r in rs:
            a = r['ASMID']
            if a == keeper or a in existing:
                continue
            m = re.search(r'hap(\d+)', a, re.IGNORECASE)
            if r['HAPLOTYPE'] in ('hap1', 'hap2'):
                suffix, why = r['HAPLOTYPE'], f"haplotype pair; plain name kept by {keeper or 'none'}"
            elif m:
                suffix, why = 'hap' + m.group(1), f"name contains hap{m.group(1)}; plain name kept by {keeper or 'none'}"
            else:
                suffix, why = 'HOLD', f"out clash with {keeper or 'another new row'}; choose a suffix"
            new_rows.append((a, suffix, why))

    c = collections.Counter(s if s == 'HOLD' else 'suffix' for _, s, _ in new_rows)
    print(f"[assign] {len(groups)} clash groups -> {len(new_rows)} new rows {dict(c)}", file=sys.stderr)
    for n in notes:
        print('[assign] ' + n, file=sys.stderr)
    for a, s, w in new_rows:
        if s == 'HOLD' or not s.startswith('hap1') and not s.startswith('hap2'):
            print(f"[assign] {s:5s} {a}  ({w})", file=sys.stderr)
    if not args.write:
        print('[assign] dry run; use --write to update ' + args.out, file=sys.stderr)
        return
    new_file = not os.path.exists(args.out)
    with open(args.out, 'a', newline='') as f:
        w = csv.writer(f, lineterminator='\n')
        if new_file:
            f.write('# Disambiguate genomes whose SPECIES+STRAIN give the same `out` results folder.\n'
                    '# SUFFIX is appended to STRAIN as <strain>_<suffix>. SUFFIX HOLD = leave the row\n'
                    '# out of samples.csv until a real suffix is chosen. Generated by\n'
                    '# scripts/assign_out_suffix.py; edit rows by hand to change a decision.\n')
            w.writerow(['ASMID', 'SUFFIX', 'REASON'])
        w.writerows(new_rows)
    print(f"[assign] appended {len(new_rows)} rows to {args.out}", file=sys.stderr)


if __name__ == '__main__':
    main()
